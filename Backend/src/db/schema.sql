CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL,
  phone VARCHAR(20) NOT NULL,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'customer'
    CHECK (role IN ('customer', 'technician', 'admin')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique_idx ON users (LOWER(email));

CREATE TABLE IF NOT EXISTS sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS password_reset_tokens_user_unique_idx
  ON password_reset_tokens (user_id);

CREATE TABLE IF NOT EXISTS service_bookings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  service_type TEXT NOT NULL CHECK (service_type IN ('repair', 'install')),
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'traveling', 'repairing', 'completed', 'cancelled')),
  ac_type TEXT NOT NULL CHECK (ac_type IN ('wall', 'ceiling')),
  btu INTEGER NOT NULL CHECK (btu IN (9000, 18000, 30000)),
  issue TEXT,
  install_work TEXT,
  appointment_date DATE NOT NULL,
  time_slot TEXT NOT NULL CHECK (time_slot IN ('morning', 'afternoon')),
  address TEXT NOT NULL,
  estimated_min INTEGER NOT NULL CHECK (estimated_min >= 0),
  estimated_max INTEGER NOT NULL CHECK (estimated_max >= estimated_min),
  technician TEXT,
  parts JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (
    (service_type = 'repair' AND issue IN ('clean', 'not_cold', 'leaking', 'not_working') AND install_work IS NULL)
    OR
    (service_type = 'install' AND install_work IN ('new', 'move') AND issue IS NULL)
  )
);

ALTER TABLE service_bookings
  ADD COLUMN IF NOT EXISTS customer_id BIGINT REFERENCES users(id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS service_bookings_customer_created_idx
  ON service_bookings (customer_id, created_at DESC);

CREATE TABLE IF NOT EXISTS service_reviews (
  booking_id BIGINT PRIMARY KEY REFERENCES service_bookings(id) ON DELETE CASCADE,
  rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment VARCHAR(500) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
