export function calculateEstimate(booking, pricing = initialPricing) {
  if (booking.serviceType === 'repair') {
    const basePrice = booking.btu <= 12000 ? pricing.repairBaseSmall : pricing.repairBaseLarge;
    const serviceFee = booking.acType === 'ceiling' ? pricing.ceilingFee : 0;
    const issueSurcharge = pricing.issueSurcharge[booking.issue];

    return {
      min: basePrice + serviceFee,
      max: basePrice + serviceFee + issueSurcharge,
    };
  }

  const basePrice = (booking.acType === 'wall' ? pricing.installWall : pricing.installCeiling) +
    (booking.btu >= 18000 ? pricing.largeBtuSurcharge : 0);
  return booking.installWork === 'move'
    ? { min: basePrice + pricing.moveMin, max: basePrice + pricing.moveMax }
    : { min: basePrice, max: basePrice };
}

