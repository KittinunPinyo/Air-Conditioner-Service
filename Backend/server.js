async function initializeSystemAdmin() {
  const email = process.env.INITIAL_ADMIN_EMAIL?.trim().toLowerCase();
  const password = process.env.INITIAL_ADMIN_PASSWORD;
  if (!email && !password) {
    console.warn('System Admin bootstrap skipped. Set INITIAL_ADMIN_EMAIL and INITIAL_ADMIN_PASSWORD in Backend/.env to create the first admin.');
    return;
  }
  if (!email || !password) {
    throw new Error('กำหนด INITIAL_ADMIN_EMAIL และ INITIAL_ADMIN_PASSWORD ให้ครบทั้งคู่ใน Backend/.env');
  }
  if (!emailPattern.test(email) || Buffer.byteLength(password, 'utf8') < 12 ||
      Buffer.byteLength(password, 'utf8') > 72) {
    throw new Error('INITIAL_ADMIN_EMAIL ไม่ถูกต้อง หรือ INITIAL_ADMIN_PASSWORD ต้องมี 12 ถึง 72 ไบต์');
  }
  const existing = await findUserByEmail(email);
  if (existing) {
    if (existing.role !== 'system_admin' && existing.role !== 'admin') {
      throw new Error('อีเมล INITIAL_ADMIN_EMAIL ถูกใช้โดยบัญชีที่ไม่ใช่ System Admin');
    }
    if (!existing.is_active) {
      await sql`UPDATE users SET is_active = TRUE WHERE id = ${existing.id}`;
    }
    return;
  }
  const passwordHash = await bcrypt.hash(password, 12);
  const user = await createUser({
    fullName: 'System Admin',
    email,
    phone: '0000000000',
    passwordHash,
    role: 'system_admin',
  });
  await sql`
    INSERT INTO audit_logs (actor_id, action, entity_type, entity_id, details)
    VALUES (NULL, 'system_admin.bootstrapped', 'user', ${user.id}, '{"role":"system_admin"}'::jsonb)
  `;
}

