function check(validator, requestProperty) {
  return (request, response, next) => {
    const result = validator(request.body);
    if (result.error) {
      response.status(400).json({ message: result.error });
      return;
    }
    request[requestProperty] = result.value;
    next();
  };
}

async function requireAuth(request, response, next) {
  const token = request.cookies?.[sessionCookieName];
  const user = await getUserForSession(token);
  if (!user) {
    response.status(401).json({ message: 'กรุณาเข้าสู่ระบบก่อนใช้งาน' });
    return;
  }

  request.user = user;
  next();
}

function requireRole(...roles) {
  const allowedRoles = new Set(roles);
  return (request, response, next) => {
    const role = request.user.role === 'admin' ? 'system_admin' : request.user.role;
    if (!allowedRoles.has(role)) {
      response.status(403).json({ message: 'คุณไม่มีสิทธิ์ใช้งานส่วนนี้' });
      return;
    }
    next();
  };
}

const imageUpload = multer({
  storage: multer.memoryStorage(),
  limits: { fileSize: 5 * 1024 * 1024, files: 1 },
  fileFilter: (request, file, callback) => {
    if (!['image/jpeg', 'image/png', 'image/webp'].includes(file.mimetype)) {
      const error = new Error('รองรับเฉพาะไฟล์ JPG, PNG หรือ WebP');
      error.status = 400;
      callback(error);
      return;
    }
    callback(null, true);
  },
});

function getImageType(buffer) {
  if (buffer.length >= 3 && buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff) {
    return { mimeType: 'image/jpeg', extension: '.jpg' };
  }
  if (buffer.length >= 8 && buffer.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))) {
    return { mimeType: 'image/png', extension: '.png' };
  }
  if (buffer.length >= 12 && buffer.toString('ascii', 0, 4) === 'RIFF' &&
      buffer.toString('ascii', 8, 12) === 'WEBP') {
    return { mimeType: 'image/webp', extension: '.webp' };
  }
  return null;
}

async function saveEvidence(request, bookingId, evidenceType) {
  if (!request.file) {
    const error = new Error('กรุณาเลือกไฟล์รูปภาพ');
    error.status = 400;
    throw error;
  }
  const imageType = getImageType(request.file.buffer);
  if (!imageType) {
    const error = new Error('ไฟล์ไม่ใช่รูปภาพ JPG, PNG หรือ WebP ที่รองรับ');
    error.status = 400;
    throw error;
  }

  const id = randomUUID();
  const storageName = `${id}${imageType.extension}`;
  await mkdir(uploadDirectory, { recursive: true });
  await writeFile(resolve(uploadDirectory, storageName), request.file.buffer, { flag: 'wx' });
  try {
    await sql`
      INSERT INTO job_evidence (id, booking_id, uploaded_by, evidence_type, storage_name, mime_type)
      VALUES (${id}, ${bookingId}, ${request.user.id}, ${evidenceType}, ${storageName}, ${imageType.mimeType})
    `;
  } catch (error) {
    try {
      await unlink(resolve(uploadDirectory, storageName));
    } catch (cleanupError) {
      console.error('Evidence file cleanup failed', {
        code: cleanupError.code || cleanupError.name || 'unknown',
      });
    }
    throw error;
  }

  await writeAudit(request, 'evidence.uploaded', 'booking', toPublicId(bookingId), { evidenceType });
  return { id, type: evidenceType, url: `/api/evidence/${id}` };
}

