app.put('/api/admin/settings/pricing', requireAuth, requireRole('system_admin'), async (request, response) => {
  const input = request.body?.settings;
  const keys = Object.keys(initialPricing);
  const issueKeys = Object.keys(initialPricing.issueSurcharge);
  const validNumber = (value) => Number.isSafeInteger(value) && value >= 0 && value <= 10000000;
  const valid = input && typeof input === 'object' &&
    keys.filter((key) => key !== 'issueSurcharge').every((key) => validNumber(input[key])) &&
    Number.isFinite(input.commissionRate) && input.commissionRate >= 0 && input.commissionRate <= 100 &&
    input.issueSurcharge && issueKeys.every((key) => validNumber(input.issueSurcharge[key]));
  if (!valid) {
    response.status(400).json({ message: 'ค่าตั้งราคาหรือเปอร์เซ็นต์คอมมิชชันไม่ถูกต้อง' });
    return;
  }
  const settings = {
    ...input,
    issueSurcharge: Object.fromEntries(issueKeys.map((key) => [key, input.issueSurcharge[key]])),
  };
  await sql`
    INSERT INTO system_settings (key, value, updated_by, updated_at)
    VALUES ('pricing', ${JSON.stringify(settings)}::jsonb, ${request.user.id}, NOW())
    ON CONFLICT (key) DO UPDATE
      SET value = EXCLUDED.value, updated_by = EXCLUDED.updated_by, updated_at = NOW()
  `;
  await writeAudit(request, 'pricing.updated', 'system_setting', 'pricing', { settings });
  response.json({ settings });
});

