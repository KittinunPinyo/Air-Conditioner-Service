async function listBookings(customerId) {
  const rows = await sql`
    SELECT b.*, r.rating AS review_rating, r.comment AS review_comment,
      t.full_name AS technician_name, p.status AS payment_status,
      category.name AS category_name,
      COALESCE((
        SELECT json_agg(json_build_object(
          'description', a.description,
          'amount', a.amount,
          'status', a.status
        ) ORDER BY a.created_at)
        FROM booking_addons a
        WHERE a.booking_id = b.id
      ), '[]'::json) AS addons
    FROM service_bookings b
    LEFT JOIN service_reviews r ON r.booking_id = b.id
    LEFT JOIN users t ON t.id = b.technician_id
    LEFT JOIN payments p ON p.booking_id = b.id
    LEFT JOIN service_categories category ON category.id = b.category_id
    WHERE b.customer_id = ${customerId}
    ORDER BY b.created_at DESC
  `;
  return rows.map(toBooking);
}

