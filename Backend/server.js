app.patch('/api/admin/users/:id', requireAuth, requireRole('system_admin'), async (request, response) => {
  const { role, isActive } = request.body || {};
  const allowedRoles = ['customer', 'technician', 'accountant', 'store_manager', 'system_admin'];
  if (!allowedRoles.includes(role) || typeof isActive !== 'boolean') {
    response.status(400).json({ message: 'บทบาทหรือสถานะบัญชีไม่ถูกต้อง' });
    return;
  }
  if (!validDatabaseId(request.params.id)) {
    response.status(400).json({ message: 'หมายเลขผู้ใช้ไม่ถูกต้อง' });
    return;
  }
  if (String(request.params.id) === request.user.id && (!isActive || role !== 'system_admin')) {
    response.status(409).json({ message: 'ไม่สามารถปิดใช้งานหรือลดสิทธิ์บัญชีที่กำลังใช้อยู่ได้' });
    return;
  }
  const [target] = await sql`SELECT id, role FROM users WHERE id = ${request.params.id}`;
  if (!target) {
    response.status(404).json({ message: 'ไม่พบบัญชีผู้ใช้' });
    return;
  }
  if ((target.role === 'system_admin' || target.role === 'admin') &&
      (role !== 'system_admin' || !isActive)) {
    const [activeAdmins] = await sql`
      SELECT COUNT(*)::integer AS count
      FROM users
      WHERE role IN ('system_admin', 'admin') AND is_active = TRUE
    `;
    if (Number(activeAdmins.count) <= 1) {
      response.status(409).json({ message: 'ต้องมี System Admin ที่ใช้งานได้อย่างน้อยหนึ่งบัญชี' });
      return;
    }
  }
  const [updated] = await sql`
    UPDATE users SET role = ${role}, is_active = ${isActive}
    WHERE id = ${request.params.id}
    RETURNING id, role, is_active AS "isActive"
  `;
  await writeAudit(request, 'user.updated', 'user', updated.id, { role, isActive });
  response.json({ user: { id: String(updated.id), role: updated.role, isActive: updated.isActive } });
});

