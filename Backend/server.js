app.get('/api/evidence/:id', requireAuth, async (request, response) => {
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(request.params.id)) {
    response.status(400).json({ message: 'หมายเลขไฟล์ไม่ถูกต้อง' });
    return;
  }
  const [evidence] = await sql`
    SELECT e.storage_name, e.mime_type, b.customer_id, b.technician_id, e.evidence_type
    FROM job_evidence e
    JOIN service_bookings b ON b.id = e.booking_id
    WHERE e.id = ${request.params.id}
  `;
  if (!evidence) {
    response.status(404).json({ message: 'ไม่พบไฟล์หลักฐาน' });
    return;
  }
  const role = request.user.role;
  const privileged = ['accountant', 'store_manager', 'system_admin', 'admin'].includes(role);
  const ownsBooking = role === 'customer' && String(evidence.customer_id) === request.user.id;
  const assignedTechnician = role === 'technician' && String(evidence.technician_id) === request.user.id;
  if (!privileged && !ownsBooking && !assignedTechnician) {
    response.status(403).json({ message: 'คุณไม่มีสิทธิ์ดูไฟล์หลักฐานนี้' });
    return;
  }
  if (!/^[0-9a-f-]{36}\.(jpg|png|webp)$/.test(evidence.storage_name)) {
    throw new Error('ชื่อไฟล์หลักฐานในฐานข้อมูลไม่ถูกต้อง');
  }
  const file = await readFile(resolve(uploadDirectory, evidence.storage_name));
  response.set('Cache-Control', 'private, no-store');
  response.set('X-Content-Type-Options', 'nosniff');
  response.type(evidence.mime_type).send(file);
});

