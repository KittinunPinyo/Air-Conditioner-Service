app.post('/api/technician/tasks/:jobId/complete', requireAuth, requireRole('technician'), async (request, response) => {
  const booking = await getAssignedBooking(request, response);
  if (!booking) return;
  if (booking.status !== 'repairing') {
    response.status(409).json({ message: 'เปลี่ยนงานเป็นกำลังซ่อมก่อนปิดงาน' });
    return;
  }
  const [evidence] = await sql`
    SELECT COUNT(DISTINCT evidence_type)::integer AS count
    FROM job_evidence
    WHERE booking_id = ${booking.id}
      AND evidence_type IN ('before', 'after')
  `;
  if (evidence.count < 2) {
    response.status(409).json({ message: 'กรุณาอัปโหลดรูปก่อนและหลังปฏิบัติงานก่อนปิดงาน' });
    return;
  }
  const [adjustments] = await sql`
    SELECT
      COALESCE(SUM(amount) FILTER (WHERE request_type = 'price_adjustment'), 0)::integer AS addons,
      COALESCE(SUM(amount) FILTER (WHERE request_type = 'discount'), 0)::integer AS discounts
    FROM manager_requests
    WHERE booking_id = ${booking.id} AND status = 'approved'
  `;
  const [pricing] = await sql`SELECT value FROM system_settings WHERE key = 'pricing'`;
  const commissionRate = Number(pricing?.value?.commissionRate ?? initialPricing.commissionRate);
  const minimumPrice = Math.max(
    0,
    Number(booking.estimated_min) + Number(adjustments.addons) - Number(adjustments.discounts),
  );
  const maximumPrice = Math.max(
    minimumPrice,
    Number(booking.estimated_max) + Number(adjustments.addons) - Number(adjustments.discounts),
  );
  const requestedPrice = request.body?.finalPrice === undefined
    ? minimumPrice
    : Number(request.body.finalPrice);
  if (!Number.isSafeInteger(requestedPrice) || requestedPrice < minimumPrice || requestedPrice > maximumPrice) {
    response.status(400).json({
      message: `ราคาสุดท้ายต้องอยู่ระหว่าง ${minimumPrice.toLocaleString()} ถึง ${maximumPrice.toLocaleString()} บาท`,
    });
    return;
  }
  const finalPrice = requestedPrice;
  const commissionAmount = Math.round(finalPrice * commissionRate / 100);
  const [completed] = await sql`
    WITH updated AS (
      UPDATE service_bookings
      SET status = 'completed',
          final_price = ${finalPrice},
          commission_rate = ${commissionRate},
          commission_amount = ${commissionAmount}
      WHERE id = ${booking.id} AND status = 'repairing'
      RETURNING id, final_price
    ),
    created_invoice AS (
      INSERT INTO invoices (invoice_number, booking_id, amount)
      SELECT 'INV-' || LPAD(id::text, 6, '0'), id, final_price
      FROM updated
      ON CONFLICT (booking_id) DO UPDATE SET amount = EXCLUDED.amount
      RETURNING id
    )
    SELECT updated.id FROM updated
  `;
  if (!completed) {
    response.status(409).json({ message: 'สถานะงานเปลี่ยนไปแล้ว กรุณาโหลดรายการใหม่' });
    return;
  }
  await writeAudit(request, 'booking.completed', 'booking', request.params.jobId, { finalPrice, commissionRate });
  response.json({ status: 'completed', finalPrice, commission: commissionAmount });
});

